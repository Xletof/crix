    dangerFrom: 0.45,
    dangerTo: 0.30,
    // Slew limits, in heat units per second. Rises fast, falls slowly, so a
    // lull does not immediately drop the music out from under the player.
    // Slew-limited rather than exponential: an exponential approach never
